"""Lesson 01 - Exercise Solutions"""

# --- Exercise 1: Print one line ---
# Simple use of print() with a single string argument.
print("I am learning Python.")


# --- Exercise 2: Name and hobby on separate lines ---
# Two independent print() calls, each producing its own line.
print("Alex")
print("Reading science fiction novels")


# --- Exercise 3: Program with an explanatory comment ---
# This program announces its author.
print("This program was written by me.")


# --- Exercise 4: Three ordered steps ---
# print() calls always run top to bottom, in the order they appear.
print("Step 1: Wake up")
print("Step 2: Learn Python")
print("Step 3: Celebrate")


# --- Exercise 5: Text box around a message ---
# Repeating a border character above and below the message creates a box.
print("****************")
print("* Hello there! *")
print("****************")


# --- Exercise 6: Sentence with an apostrophe ---
# Double quotes are used here so the apostrophe inside the sentence
# does not end the string early.
print("It's a beautiful day to code.")


# --- Exercise 7: A small receipt ---
print("Corner Bookstore")
print("1x Python Fundamentals Notebook - $12.00")
print("1x Pencil Set - $3.00")
print("Total: $15.00")


# --- Exercise 8: Two commented sections ---
# Section 1: greet the user
print("Hello and welcome!")

# Section 2: give the user instructions
print("Please follow along with today's lesson.")


# --- Exercise 9: Small ASCII triangle ---
print("*")
print("**")
print("***")


# --- Exercise 10: Fictional terminal session ---
print("$ python3 main.py")
print("Loading configuration...")
print("Connecting to server...")
print("Connection established.")
print("Program finished successfully.")
